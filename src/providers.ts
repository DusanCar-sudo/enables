// and key env var names.  When the user picks a provider, this table tells
// the proxy everything it needs.

export interface ProviderDef {
  id: string;
  name: string;
  group?: string;
  variant?: string;
  adapter: 'openai' | 'anthropic';
  baseUrl: string;           // OpenAI-compatible base URL (chat/completions)
  keyPrompt: string;          // What to ask the user for
  keyHint: string;            // Example / format hint
  keyEnvVar: string;          // Env var name for reference
  defaultModel: string;       // Default target model
  models: string[];           // Available target models for this provider
  isCustom?: boolean;          // Ask for base URL and model at setup time
  notes?: string;             // Any special notes
  freeTier?: boolean;          // Participates in the default free-first failover chain
  tier?: number;               // 1 = best free quality, ascending = lower preference
  noKeyRequired?: boolean;     // Usable without any API key (local / open gateways)
}

